"""笔记领域包。

本包按三层落，**目前只有第一层在位**：

- ``types/``（在位）—— **数据结构**：一条写法——继承 ``Block``、**声明写在类体上**
  （``title: str = Attr("")`` / ``lines: list[NoteLine] = Body([])``）。继承 ``Block``
  的是**载体**（有身份、有表、可单独落盘）；其余是**载荷内的结构**（值对象，
  只活在别人的载荷里）；
- ``format/``（待落）—— **编解码**：载荷的规范化字节
  （同一逻辑内容必须编出同一段字节，否则内容地址会漂、去重失效）。它未落地之前，
  载荷里的 dataclass（如 `NoteLine`）编不成字节，故载体字段的往返只覆盖可编码的那些值；
- ``engine/``（待落）—— **重度算法**：区间归并、偏移重算、路径求值一类。
  它**只依赖 ``types/``**，不依赖领域服务，故能脱离内核单测，也能被别处直接引用。

``exc.py``（在位）是这一族的异常；领域服务与命令面随后落在本包根上。
"""
