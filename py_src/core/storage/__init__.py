"""存储层:文件里是格,每格 = 槽头 + 内容;块由属性槽与正文槽组成.

四层,每层只管下一层:

| 层 | 管什么 |
|---|---|
| `pack.py` | 一个载体文件:文件头,槽头,两类槽的读写与顺扫 |
| `hub.py` | 一个目录:挑活跃载体,封口换份(多 hub 对上是分组) |
| `engine.py` | 块 ↔ 槽:分配,编码,落盘,读回;`Block` 基座在这里 |

`db/id.py` 在四层之上管**身份与段算术**:段列表的规范形与其编解码,正文历史,都在那一处.

五处辅助:

- `conf.py` 是**这一层的配置声明**(格长两档,封口线,默认 hub,索引块上限,正文历史深度,
  自动回收阈值);
- `types.py` 是**声明形态**:`Attr` / `Body` 两个描述符,决定字段落在哪一边;
- `db/` 是**身份与索引库**(索引库是权威视角:一个类型一张身份表);
- `index/` 放索引块(正表行落在载体的槽上,反表读时现算);
- `gc.py` 是**引擎的另一种确定性形态**:按索引库收活槽,把没人要的字节抹掉.
"""
