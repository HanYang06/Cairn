"""存储层：文件里是格，块存在文件里，一个块可以跨多个格。

四层，每层只管下一层：

| 层 | 管什么 |
|---|---|
| `slot.py` | 一个文件内的等长格：算术定位（不读盘、不读配置） |
| `pack.py` | 一个载体文件：记录框定与身份、追加写、顺扫 |
| `hub.py` | 一个目录：挑活跃载体、封口换份（多 hub 对上是分组） |
| `engine.py` | 块 ↔ 记录：分配、编码、落盘、读回；`Block` 基座在这里 |

五处辅助：

- `conf.py` 是**这一层的配置声明**（格长五档、封口线、默认 hub、索引块上限）；
- `types.py` 是**声明形态**：`Attr` / `Body` 两个描述符，决定字段落在哪一边；
- `db/` 是**数据库引擎**（索引库：一个类型一张身份表）；
- `index/` 放索引块（正表存在块里，反表读时现算）；
- `gc.py` 是**引擎的另一种确定性形态**：同一批文件、换一套判据，把没人要的字节抹掉。
"""
